#!/usr/bin/env python3
"""Cut the full Noto Serif JP / Noto Sans JP fonts into small unicode-range slices.

Why: the full files are 5.6 MB and 4.2 MB. A page only ever needs the characters on it, so we ship the app's
own character set in slices (core = kana, punctuation and the few characters the UI prints; every other kanji by frequency, 150 per slice)
and let the browser fetch only the slices a page touches. The full fonts stay available for the card font picker.

Run by hand when public/data or UI strings change, then commit the output:
    python3 -m venv .venv && .venv/bin/pip install fonttools brotli
    .venv/bin/python scripts/subset-fonts.py

Reads : src/assets/fonts/noto-{serif,sans}-jp.woff2, public/data/*.json, src/**/*.{ts,tsx,css}, index.html
Writes: src/assets/fonts/jp/{serif,sans}-NN.woff2 and src/styles/jp-fonts.generated.css
"""
import sys
from io import BytesIO
from collections import Counter
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / 'src/assets/fonts'
OUT = FONTS / 'jp'
CSS = ROOT / 'src/styles/jp-fonts.generated.css'
SLICE = 150
# One static weight per family: a variable weight axis doubles the size, and the app sets these fonts at regular weight
# (seals and furigana use font-synthesis: none, so they simply take the nearest face).
FAMILIES = {'serif': ('SN Serif JP', 'noto-serif-jp.woff2', 400), 'sans': ('SN Sans JP', 'noto-sans-jp.woff2', 500)}

def is_kanji(cp: int) -> bool:
    return 0x4E00 <= cp <= 0x9FFF or 0x3400 <= cp <= 0x4DBF or 0xF900 <= cp <= 0xFAFF

def wanted(cp: int) -> bool:
    """Latin and Vietnamese letters come from Be Vietnam Pro / Newsreader, so the JP fonts only carry what those lack."""
    return cp >= 0x2000 and not (0x1E00 <= cp < 0x1F00)

def collect():
    freq = Counter()
    for path in sorted((ROOT / 'public/data').glob('*.json')):
        freq.update(c for c in path.read_text(encoding='utf-8') if wanted(ord(c)))
    chrome, rest = set(), set()  # characters the interface itself prints vs. characters in other source (exam text...)
    skip = ('assets/fonts', 'examData')
    for path in [p for pattern in ('src/**/*.ts', 'src/**/*.tsx', 'src/**/*.css') for p in ROOT.glob(pattern)] + [ROOT / 'index.html']:
        if any(part in str(path) for part in skip) or path.name.endswith('.generated.css'): continue
        (chrome if path.suffix in ('.tsx', '.css', '.html') else rest).update(c for c in path.read_text(encoding='utf-8') if wanted(ord(c)))
    exam = (ROOT / 'src/components/listening/examData.ts').read_text(encoding='utf-8')
    rest.update(c for c in exam if wanted(ord(c)))
    # ASCII, CJK punctuation, hiragana and katakana. Anything else (fullwidth forms, arrows, symbols) joins core only if
    # the data or the interface really prints it, so the slice every page needs stays small.
    fixed = set(range(0x20, 0x7F)) | set(range(0x3000, 0x3040)) | set(range(0x3041, 0x3097)) | set(range(0x309B, 0x30A0)) \
        | set(range(0x30A1, 0x3100))
    return freq, chrome, rest, fixed

def make_slices(freq, chrome, rest, fixed):
    # core: what every page can touch (kana, punctuation, the characters the interface itself prints).
    core = set(fixed) | {ord(c) for c in chrome} | {ord(c) for c in freq if not is_kanji(ord(c))}
    # Every other kanji (data and exam text) goes into slices ordered by how often the data uses it.
    pool = {c for c in set(freq) | rest if is_kanji(ord(c)) and ord(c) not in core}
    ordered = sorted(pool, key=lambda c: (-freq[c], c))
    slices = [sorted(core)] + [sorted(ord(c) for c in ordered[i:i + SLICE]) for i in range(0, len(ordered), SLICE)]
    seen = set()
    for index, group in enumerate(slices):  # every code point lives in exactly one slice
        assert not (seen & set(group)), f'slice {index} overlaps an earlier one'
        seen |= set(group)
    return slices, pool

def ranges(codepoints):
    out, start, prev = [], None, None
    for cp in codepoints:
        if start is None: start = prev = cp
        elif cp == prev + 1: prev = cp
        else: out.append((start, prev)); start = prev = cp
    if start is not None: out.append((start, prev))
    return ', '.join(f'U+{a:04X}' if a == b else f'U+{a:04X}-{b:04X}' for a, b in out)

def main():
    freq, chrome, rest, fixed = collect()
    slices, pool = make_slices(freq, chrome, rest, fixed)
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob('*.woff2'): old.unlink()
    css = ['/* Generated by scripts/subset-fonts.py. Do not edit. */']
    total = 0
    for key, (family, source, weight) in FAMILIES.items():
        instanced = instancer.instantiateVariableFont(TTFont(FONTS / source), {'wght': weight}, inplace=False)
        buffer = BytesIO(); instanced.save(buffer); blob = buffer.getvalue()  # re-opened per slice: the subsetter edits in place
        covered = set(instanced.getBestCmap())
        for index, group in enumerate(slices):
            present = [cp for cp in group if cp in covered]
            if not present: continue
            options = subset.Options()
            options.flavor = 'woff2'; options.layout_features = ['*']; options.hinting = False
            options.notdef_outline = True; options.name_IDs = [1, 2, 3, 4, 6]; options.glyph_names = False
            work = TTFont(BytesIO(blob))
            subsetter = subset.Subsetter(options); subsetter.populate(unicodes=present); subsetter.subset(work)
            file = OUT / f'{key}-{index:02d}.woff2'
            work.flavor = 'woff2'; work.save(file)
            size = file.stat().st_size; total += size
            css.append(f"@font-face {{ font-family: '{family}'; src: url('../assets/fonts/jp/{file.name}') format('woff2'); font-weight: {weight}; font-style: normal; font-display: swap; unicode-range: {ranges(present)}; }}")
            print(f'{file.name}: {len(present)} chars, {size // 1024} KB')
    CSS.parent.mkdir(parents=True, exist_ok=True)
    CSS.write_text('\n'.join(css) + '\n', encoding='utf-8')
    print(f'\n{len(slices)} slices per family, {total // 1024} KB in total. Every data character is covered:')
    placed = set().union(*map(set, slices))
    missing = [c for c in pool if ord(c) not in placed]
    assert not missing, f'uncovered: {missing[:10]}'
    print('ok')

if __name__ == '__main__':
    sys.exit(main())
