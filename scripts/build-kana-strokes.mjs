// Bundles KanjiVG stroke paths (CC BY-SA 3.0, kanjivg.tagaini.net) for the 92 basic kana.
// Run: node scripts/build-kana-strokes.mjs
import { writeFileSync } from 'node:fs';

const CHARS = 'あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをんアイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン';
const out = {};
for (const ch of CHARS) {
  const hex = ch.codePointAt(0).toString(16).padStart(5, '0');
  const res = await fetch(`https://cdn.jsdelivr.net/gh/KanjiVG/kanjivg@master/kanji/${hex}.svg`);
  if (!res.ok) throw new Error(`${ch} ${hex}: HTTP ${res.status}`);
  const svg = await res.text();
  out[ch] = [...svg.matchAll(/<path id="kvg:[0-9a-f]+-s\d+"[^>]* d="([^"]+)"/g)].map(m => m[1]);
  if (!out[ch].length) throw new Error(`${ch}: no strokes`);
}
const header = '// Generated by scripts/build-kana-strokes.mjs from KanjiVG (CC BY-SA 3.0, https://kanjivg.tagaini.net). Do not edit.\n';
writeFileSync(new URL('../src/components/kana/kanaStrokes.ts', import.meta.url), `${header}export const KANA_STROKES: Record<string, string[]> = ${JSON.stringify(out)};\n`);
console.log(Object.entries(out).map(([k, v]) => k + v.length).join(' '));
