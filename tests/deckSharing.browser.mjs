import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from 'playwright';

const server = await createServer({ server: { host: '127.0.0.1', port: 0, open: false } });
await server.listen();
const base = server.resolvedUrls.local[0].replace(/\/$/, '');
const token = '11111111-1111-4111-8111-111111111111';
const deckId = '22222222-2222-4222-8222-222222222222';
const user = { id: 'learner', email: 'learner@example.com', displayName: 'Bạn học' };
const personal = { id: deckId, name: 'Từ vựng cùng học', sourceType: 'IMPORT', cardCount: 1, templateConfig: {}, position: 0, newCount: 1, dueCount: 0, tags: [], groupId: null, version: 0 };
const paged = content => ({ content, number: 0, totalPages: content.length ? 1 : 0, totalElements: content.length, size: 20 });
let browser;
let link = null;
let revoked = false;
let copyCalls = 0;
let failPreview = false;
let previewCardCount = 103;
const errors = [];
const output = 'artifacts/deck-sharing';
await mkdir(output, { recursive: true });
try {
  browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL || undefined });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce', permissions: ['clipboard-read', 'clipboard-write'] });
  await context.route('**/api/v1/**', async route => {
    const request = route.request();
    const path = new URL(request.url()).pathname.replace('/api/v1', '');
    const method = request.method();
    const reply = (body, status = 200) => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(body) });
    if (path === `/shared-decks/${token}`) {
      assert.equal(request.headers().authorization, undefined);
      if (failPreview) return reply({ message: 'Tạm thời mất kết nối' }, 503);
      if (revoked) return reply({ message: 'Liên kết đã ngừng chia sẻ.' }, 404);
      const page = Number(new URL(request.url()).searchParams.get('page') || 0);
      const start = page * 50;
      const previewCount = Math.ceil(previewCardCount / 2);
      const cards = Array.from({ length: Math.max(0, Math.min(50, previewCount - start)) }, (_, index) => ({ front: `猫 ${start + index}`, back: start + index === 0 ? 'Con mèo' : `Nghĩa ${start + index}`, reading: 'ねこ', kind: 'VOCABULARY' }));
      return reply({ name: personal.name, description: 'Cùng học mỗi ngày', author: 'Người gửi', cardCount: previewCardCount, previewCount, page, size: 50, totalPages: Math.ceil(previewCount / 50), cards });
    }
    if (path === '/auth/login') return reply({ accessToken: 'fixture', refreshToken: 'fixture-refresh', user });
    if (path === '/auth/me') return reply(user);
    if (path === '/users/me/learning') return reply({ revision: 0, bookmarks: [], srsCards: [], studyDays: [] });
    if (path === '/users/me/settings') return reply({ theme: 'light', fontSize: 'medium', dailyGoal: 20, reducedMotion: true });
    if (path === '/deck-groups') return reply([]);
    if (path === '/decks') return reply(paged([personal]));
    if (path === `/decks/${deckId}/metadata`) return reply(personal);
    if (path === `/decks/${deckId}/cards`) return reply(paged([{ id: 'card', deckId, front: '猫', back: 'Con mèo', kind: 'VOCABULARY', extraData: {}, position: 0 }]));
    if (path === `/decks/${deckId}/share`) {
      if (method === 'PUT') { link = token; revoked = false; }
      if (method === 'DELETE') { link = null; revoked = true; return route.fulfill({ status: 204 }); }
      return reply({ token: link });
    }
    if (path === `/shared-decks/${token}/copy`) {
      assert.equal(request.headers().authorization, 'Bearer fixture');
      copyCalls++;
      await new Promise(resolve => setTimeout(resolve, 150));
      return reply({ deckId, alreadySaved: copyCalls > 1 });
    }
    return reply({ message: `Unhandled fixture ${method} ${path}` }, 500);
  });
  const page = await context.newPage();
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/shared/${token}`);
  await page.getByRole('heading', { name: personal.name, exact: true }).waitFor();
  assert.equal(await page.getByText('Con mèo', { exact: true }).count(), 1);
  assert.equal(await page.getByRole('dialog').count(), 0);
  await page.getByText('Xem trước 52 / 103 thẻ', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Trang tiếp', exact: true }).click();
  await page.getByText('THẺ 51', { exact: true }).waitFor();
  assert.equal(await page.locator('section[aria-labelledby="shared-preview"] article').count(), 2);
  assert.equal(await page.getByRole('button', { name: 'Trang tiếp', exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Trang trước', exact: true }).click();
  await page.getByText('THẺ 1', { exact: true }).waitFor();
  previewCardCount = 3;
  await page.getByRole('button', { name: 'Trang tiếp', exact: true }).click();
  await page.getByText('Xem trước 2 / 3 thẻ', { exact: true }).waitFor();
  assert.equal(await page.locator('section[aria-labelledby="shared-preview"] article').count(), 2);
  assert.equal(await page.getByText('THẺ 1', { exact: true }).count(), 1);
  previewCardCount = 103;
  await page.reload();
  await page.getByText('Xem trước 52 / 103 thẻ', { exact: true }).waitFor();
  await page.screenshot({ path: `${output}/preview-desktop.png` });
  await page.getByRole('button', { name: 'Đăng nhập để lưu bộ thẻ' }).click();
  await page.getByRole('button', { name: 'Tiếp tục học thử', exact: true }).click();
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(new URL(page.url()).pathname, `/shared/${token}`);
  await page.getByRole('button', { name: 'Đăng nhập để lưu bộ thẻ' }).click();
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).click();
  await page.getByLabel('Email', { exact: true }).fill(user.email);
  await page.getByLabel('Mật khẩu', { exact: true }).fill('Password123!');
  await page.locator('form button.auth-submit').click();
  await page.getByRole('button', { name: 'Lưu vào bộ thẻ của tôi' }).waitFor();
  assert.equal(new URL(page.url()).pathname, `/shared/${token}`);
  await page.getByRole('button', { name: 'Lưu vào bộ thẻ của tôi' }).click();
  await page.getByText('Đã lưu vào bộ thẻ của bạn.', { exact: true }).waitFor();
  assert.equal(copyCalls, 1);
  await page.getByRole('link', { name: 'Mở bộ thẻ để học' }).click();
  await page.getByRole('heading', { name: `${personal.name} · 1 thẻ`, exact: true }).waitFor();
  await page.getByRole('button', { name: 'Chia sẻ', exact: true }).click();
  await page.getByRole('button', { name: 'Tạo liên kết chia sẻ' }).click();
  await page.getByLabel('Liên kết chia sẻ', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Sao chép liên kết' }).click();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), `${base}/shared/${token}`);
  await page.screenshot({ path: `${output}/share-dialog-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: `${output}/share-dialog-mobile.png`, fullPage: true });
  const dialogBox = await page.getByRole('dialog').boundingBox();
  assert.ok(dialogBox.x >= 0 && dialogBox.x + dialogBox.width <= 390);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: 'Đóng', exact: true }).click();
  await page.getByRole('button', { name: '← Các bộ thẻ' }).click();
  await page.getByRole('button', { name: `Thao tác với bộ ${personal.name}` }).click();
  await page.getByRole('menuitem', { name: 'Chia sẻ bộ thẻ', exact: true }).click();
  await page.getByRole('button', { name: 'Ngừng chia sẻ' }).click();
  await page.getByRole('button', { name: 'Giữ liên kết' }).click();
  assert.equal(link, token);
  await page.getByRole('button', { name: 'Ngừng chia sẻ' }).click();
  await page.getByRole('button', { name: 'Tắt liên kết', exact: true }).click();
  await page.getByRole('button', { name: 'Tạo liên kết chia sẻ' }).waitFor();
  assert.equal(link, null);
  await page.goto(`${base}/shared/${token}`);
  await page.getByRole('heading', { name: 'Liên kết không còn khả dụng' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Lưu vào bộ thẻ của tôi' }).count(), 0);
  revoked = false;
  failPreview = true;
  await page.reload();
  await page.getByRole('heading', { name: 'Chưa thể hoàn tất' }).waitFor();
  failPreview = false;
  await page.getByRole('button', { name: 'Thử tải lại' }).click();
  await page.getByRole('button', { name: 'Lưu vào bộ thẻ của tôi' }).click();
  await page.getByText('Bộ thẻ này đã có trong thư viện của bạn.', { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Trang tiếp', exact: true }).click();
  await page.getByText('THẺ 51', { exact: true }).waitFor();
  await page.screenshot({ path: `${output}/preview-mobile.png`, fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  assert.deepEqual(errors, []);
  console.log('PASS: public preview, login preserves link, saving, direct deck opening, both sharing entry points, clipboard, revoke/cancel, duplicate save, retry, mobile layout');
} finally { await browser?.close(); await server.close(); }
